#!/usr/bin/env node
/**
 * Regenerate `src/ui/icons.js` from the jigsaw-piece SVG (issue #164).
 *
 * The tray adapter carries the two 16x16 PNGs as base64 strings so the
 * always-on path never imports an image library. That leaves a hand-edited
 * base64 blob, which nobody can review. So the geometry lives in
 * `src/ui/icons/tray-piece.svg`, this script rasterises it with `sharp`
 * (already a dependency, used only here and in tests), and the generated
 * `src/ui/icons.js` is committed for the runtime.
 *
 *   node scripts/build-tray-icons.mjs              # rewrite src/ui/icons.js
 *   node scripts/build-tray-icons.mjs --preview    # also write the review PNG
 *
 * The SVG is the blue state; the grey state is the same geometry with the two
 * colour tokens substituted, so the shape can never drift between states.
 */
import sharp from 'sharp';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SVG_PATH = join(root, 'src/ui/icons/tray-piece.svg');
const OUT_PATH = join(root, 'src/ui/icons.js');
const PREVIEW_PATH = join(root, 'src/ui/icons/tray-piece-preview.png');

// The tokens as they appear in the committed SVG.
const BLUE = { fill: '#1e78dc', stroke: '#0a3d73' };
const GREY = { fill: '#969696', stroke: '#4a4a4a' };

const STATES = [
  { key: 'normal', varName: 'BLUE_PIECE_16', palette: BLUE },
  { key: 'grey', varName: 'GREY_PIECE_16', palette: GREY },
];

const source = readFileSync(SVG_PATH, 'utf8');

/** The geometry with this state's colours, keeping the tab and blank identical. */
function svgFor({ fill, stroke }) {
  return source
    .replace(`fill="${BLUE.fill}"`, `fill="${fill}"`)
    .replace(`stroke="${BLUE.stroke}"`, `stroke="${stroke}"`);
}

/** Rasterise one state to its 16x16 PNG. */
function render(svgText) {
  return sharp(Buffer.from(svgText), { density: 384 })
    .resize(16, 16, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } })
    .png()
    .toBuffer();
}

const pngs = {};
for (const state of STATES) {
  pngs[state.key] = await render(svgFor(state.palette));
}

const declarations = STATES.map(
  (s) => `const ${s.varName} =\n  '${pngs[s.key].toString('base64')}';`
).join('\n');

const module = `/**
 * Tray icon bitmaps.
 *
 * Two 16x16 PNGs of a jigsaw puzzle piece, embedded as base64 rather than generated
 * at runtime: the tray adapter must not pull \`sharp\` (or any image library) into the
 * always-on path just to colour a pixel. \`normal\` is the app listening; \`grey\` is the
 * watchdog's "the listener has gone quiet" state (DESIGN 7). Colour is the state
 * signal, the shape is the identity.
 *
 * Generated by \`scripts/build-tray-icons.mjs\` from \`src/ui/icons/tray-piece.svg\`.
 * Do not edit the base64 by hand: edit the SVG and re-run the script.
 *
 * \`systray2\` wants raw base64 without the \`data:\` prefix.
 */

${declarations}

export const TRAY_ICONS = {
  normal: ${STATES[0].varName},
  grey: ${STATES[1].varName},
};

/** Icon payload for a state name; unknown states fall back to \`normal\`. */
export function trayIcon(state) {
  return TRAY_ICONS[state] ?? TRAY_ICONS.normal;
}
`;

writeFileSync(OUT_PATH, module);
console.log(`wrote ${OUT_PATH}`);

if (process.argv.includes('--preview')) {
  // A 2x2 contact sheet of the *actual* 16px bitmaps, nearest-upscaled 8x, on a
  // light and a dark background - the thing a reviewer cannot see in a diff.
  const scale = 8;
  const cell = 16 * scale;
  const pad = 12;
  const size = pad * 3 + cell * 2;
  const backgrounds = [
    { top: pad, left: pad, colour: '#f4f4f4' },
    { top: pad, left: pad * 2 + cell, colour: '#f4f4f4' },
    { top: pad * 2 + cell, left: pad, colour: '#1e1e1e' },
    { top: pad * 2 + cell, left: pad * 2 + cell, colour: '#1e1e1e' },
  ];
  const tiles = await Promise.all(
    [0, 1, 2, 3].map((i) =>
      sharp(pngs[i % 2 === 0 ? 'normal' : 'grey'])
        .resize(cell, cell, { kernel: 'nearest' })
        .png()
        .toBuffer()
    )
  );
  const sheet = sharp({
    create: { width: size, height: size, channels: 4, background: '#00000000' },
  });
  const composites = [];
  backgrounds.forEach((bg, i) => {
    composites.push({
      input: { create: { width: cell, height: cell, channels: 4, background: bg.colour } },
      top: bg.top,
      left: bg.left,
    });
    composites.push({ input: tiles[i], top: bg.top, left: bg.left });
  });
  await sheet.composite(composites).png().toFile(PREVIEW_PATH);
  console.log(`wrote ${PREVIEW_PATH}`);
}
